"""Aggregate transcripts/ into results/summary.md and results/summary.json.

Metrics per model
  mean score     : partial-credit score averaged over all task x trial attempts,
                   with the spread (min-max and SD) of the per-trial-round means
  strict pass    : share of attempts where every component is correct
  pass@k         : share of tasks solved strictly in at least one of k trials
  pass^k         : share of tasks solved strictly in all k trials
  pair pass^k    : share of contrast pairs where BOTH tasks pass in every trial
  routing errors : clinically important mistakes, counted over all attempts
"""
import json
import statistics as st
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TASKS = {json.loads(p.read_text(encoding="utf-8"))["id"]: json.loads(p.read_text(encoding="utf-8"))
         for p in (ROOT / "tasks").glob("T*.json")}


def load():
    runs = defaultdict(list)
    for f in sorted((ROOT / "transcripts").glob("*/*.json")):
        r = json.loads(f.read_text(encoding="utf-8"))
        runs[f.parent.name].append(r)
    return runs


def summarize(records):
    by_task = defaultdict(list)
    by_trial = defaultdict(list)
    for r in records:
        by_task[r["task_id"]].append(r)
        by_trial[r["trial"]].append(r["grade"]["score"])
    k = min(len(v) for v in by_task.values())
    scores = [r["grade"]["score"] for r in records]
    round_means = [st.mean(v) for v in by_trial.values() if len(v) == len(by_task)]
    task_rows = {}
    for tid, rs in sorted(by_task.items()):
        passes = [r["grade"]["strict_pass"] for r in rs]
        comps = defaultdict(list)
        for r in rs:
            for c, v in r["grade"]["components"].items():
                comps[c].append(v)
        task_rows[tid] = {
            "trials": len(rs), "mean_score": round(st.mean(r["grade"]["score"] for r in rs), 3),
            "strict_passes": sum(passes), "pass_at_k": any(passes), "pass_hat_k": all(passes),
            "errors": dict(Counter(r["grade"]["error"] for r in rs if r["grade"]["error"])),
            "components": {c: round(st.mean(v), 2) for c, v in comps.items()},
            "diagnoses": dict(Counter(r["grade"]["detail"].get("diagnosis") for r in rs)),
            "next_steps": dict(Counter(r["grade"]["detail"].get("next_step") for r in rs)),
            "totals": [r["grade"]["detail"].get("total") for r in rs],
            "label_errors": [r["grade"]["detail"].get("label_errors") for r in rs if r["grade"]["detail"].get("label_errors")],
        }
    pairs = defaultdict(list)
    for tid in task_rows:
        pairs[TASKS[tid]["pair"]].append(task_rows[tid]["pass_hat_k"])
    item_errs = [e for r in records for e in (r["grade"]["detail"].get("item_abs_err") or [])]
    meta0 = records[0]
    versions = set()
    cost = 0.0
    for r in records:
        m = r.get("meta") or {}
        if m.get("model_version"):
            versions.add(m["model_version"])
        for name in (m.get("model_usage") or {}):
            versions.add(name)
        cost += m.get("cost_usd") or 0.0
    return {
        "backend": meta0["backend"], "model": meta0["model"], "model_versions": sorted(versions),
        "temperature": meta0["temperature"], "trials_per_task": k, "attempts": len(records),
        "mean_score": round(st.mean(scores), 3),
        "round_mean_min": round(min(round_means), 3) if round_means else None,
        "round_mean_max": round(max(round_means), 3) if round_means else None,
        "round_mean_sd": round(st.stdev(round_means), 3) if len(round_means) > 1 else None,
        "strict_pass_rate": round(sum(r["grade"]["strict_pass"] for r in records) / len(records), 3),
        "pass_at_k": round(sum(t["pass_at_k"] for t in task_rows.values()) / len(task_rows), 3),
        "pass_hat_k": round(sum(t["pass_hat_k"] for t in task_rows.values()) / len(task_rows), 3),
        "pair_pass_hat_k": round(sum(all(v) for v in pairs.values()) / len(pairs), 3),
        "routing_errors": dict(Counter(r["grade"]["error"] for r in records
                                       if r["grade"]["error"] not in (None, "component_error"))),
        "item_mae": round(st.mean(item_errs), 2) if item_errs else None,
        "cost_usd_logged": round(cost, 4),
        "mean_latency_s": round(st.mean(r["latency_s"] for r in records), 1),
        "dates": sorted({r["timestamp_utc"][:10] for r in records}),
        "tasks": task_rows,
    }


def main():
    runs = load()
    out = {name: summarize(recs) for name, recs in runs.items() if recs}
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "summary.json").write_text(json.dumps(out, indent=2), encoding="utf-8")

    L = ["# Results", "", "Generated by `python summarize.py` from `transcripts/`.", "",
         "| Run | Versions | Trials/task | Mean score (round min-max) | Strict pass | pass@k | pass^k | Pair pass^k | Item MAE | Logged cost | Dates |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, s in sorted(out.items()):
        L.append(f"| {name} | {', '.join(s['model_versions']) or '-'} | {s['trials_per_task']} | "
                 f"{s['mean_score']:.2f} ({s['round_mean_min']}-{s['round_mean_max']}) | {s['strict_pass_rate']:.0%} | "
                 f"{s['pass_at_k']:.0%} | {s['pass_hat_k']:.0%} | {s['pair_pass_hat_k']:.0%} | {s['item_mae']} | "
                 f"${s['cost_usd_logged']:.3f} | {', '.join(s['dates'])} |")
    L += ["", "## Clinically important routing errors (count over all attempts)", "",
          "| Run | OCD sent to urgent risk | Real risk missed | OCD called psychosis | False OCD | Missed OCD | Wrong OCD intensity |",
          "|---|---|---|---|---|---|---|"]
    for name, s in sorted(out.items()):
        e = s["routing_errors"]
        L.append(f"| {name} | {e.get('ocd_misrouted_as_risk', 0)} | {e.get('missed_real_risk', 0)} | "
                 f"{e.get('ocd_called_psychosis', 0)} | {e.get('false_ocd', 0)} | {e.get('missed_ocd', 0)} | "
                 f"{e.get('wrong_ocd_intensity', 0)} |")
    L += ["", "## Per task: strict passes / trials (mean partial-credit score)", ""]
    names = sorted(out)
    L.append("| Task | " + " | ".join(names) + " |")
    L.append("|---|" + "---|" * len(names))
    for tid in sorted(TASKS):
        cells = []
        for n in names:
            t = out[n]["tasks"].get(tid)
            cells.append(f"{t['strict_passes']}/{t['trials']} ({t['mean_score']:.2f})" if t else "-")
        L.append(f"| {tid} | " + " | ".join(cells) + " |")
    L += ["", "## Per task detail", ""]
    for tid in sorted(TASKS):
        L.append(f"### {tid}")
        for n in names:
            t = out[n]["tasks"].get(tid)
            if not t:
                continue
            L.append(f"- **{n}**: diagnoses {t['diagnoses']}, next steps {t['next_steps']}, "
                     f"totals {t['totals']}, components {t['components']}")
            for le in t["label_errors"][:3]:
                L.append(f"  - label errors: {le}")
        L.append("")
    L += chat_section()
    L += multi_section()
    (ROOT / "results" / "summary.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


def chat_section():
    """Part B: companion-app behaviour, judged per check."""
    runs = defaultdict(list)
    for f in sorted((ROOT / "transcripts_chat").glob("*/*.json")):
        runs[f.parent.name].append(json.loads(f.read_text(encoding="utf-8")))
    if not runs:
        return []
    tasks = {json.loads(p.read_text(encoding="utf-8"))["id"]: json.loads(p.read_text(encoding="utf-8"))
             for p in (ROOT / "tasks_chat").glob("C*.json")}
    ocd_tasks = [t for t in sorted(tasks) if "reassurance" in t]
    L = ["", "# Part B: companion-app behaviour", "",
         "| Run | Judge | Trials/task | Mean score | Strict pass (all) | Strict pass (OCD tasks) | Strict pass (controls) | pass^k | Pair pass^k |",
         "|---|---|---|---|---|---|---|---|---|"]
    per_model = {}
    for name, recs in sorted(runs.items()):
        by_task = defaultdict(list)
        for r in recs:
            by_task[r["task_id"]].append(r)
        k = min(len(v) for v in by_task.values())
        sp = lambda rs: sum(r["grade"]["strict_pass"] for r in rs) / len(rs)  # noqa: E731
        ocd = [r for r in recs if r["task_id"] in ocd_tasks]
        ctl = [r for r in recs if r["task_id"] not in ocd_tasks]
        hat = {t: all(r["grade"]["strict_pass"] for r in rs) for t, rs in by_task.items()}
        pairs = defaultdict(list)
        for t, v in hat.items():
            pairs[tasks[t]["pair"]].append(v)
        per_model[name] = by_task
        L.append(f"| {name} | {recs[0]['judge']} | {k} | "
                 f"{st.mean(r['grade']['score'] for r in recs):.2f} | {sp(recs):.0%} | "
                 f"{sp(ocd) if ocd else 0:.0%} | {sp(ctl) if ctl else 0:.0%} | "
                 f"{sum(hat.values())/len(hat):.0%} | {sum(all(v) for v in pairs.values())/len(pairs):.0%} |")
    L += ["", "## Part B: how often each failure happened (attempts where the check failed / attempts)", ""]
    names = sorted(per_model)
    L.append("| Task | Check | " + " | ".join(n for n in names) + " |")
    L.append("|---|---|" + "---|" * len(names))
    for t in sorted(tasks):
        for c in tasks[t]["checks"]:
            cells = []
            for n in names:
                rs = per_model[n].get(t, [])
                cells.append(f"{sum(r['grade']['components'][c['id']] < 1 for r in rs)}/{len(rs)}" if rs else "-")
            L.append(f"| {t} | {c['kind']} {c['id']} | " + " | ".join(cells) + " |")
    L += ["", "## Part B: example evidence quoted by the judge", ""]
    for n in names:
        for t, rs in sorted(per_model[n].items()):
            for r in rs:
                for cid, d in r["grade"]["detail"].items():
                    if r["grade"]["components"][cid] < 1 and d.get("evidence"):
                        L.append(f"- **{n}** {t} t{r['trial']} `{cid}`: \"{d['evidence'][:220]}\"")
                        break
    return L



def multi_section():
    """Part C: multi-turn reassurance pressure ("hold the line")."""
    runs = defaultdict(list)
    for f in sorted((ROOT / "transcripts_multi").glob("*/*.json")):
        runs[f.parent.name].append(json.loads(f.read_text(encoding="utf-8")))
    if not runs:
        return []
    L = ["", "# Part C: multi-turn reassurance pressure", "",
         "Turn 0 = the Part B message; turns 1-4 = scripted pressure (1 fact reframe, 2 bargain, 3 guilt, 4 ask someone else).", "",
         "| Run | Judge | Conversations | Mean turns held (of 5) | Held all 5 | pass^k (per task) | First break at turn 0/1/2/3/4 |",
         "|---|---|---|---|---|---|---|"]
    detail = []
    for name, recs in sorted(runs.items()):
        by_task = defaultdict(list)
        for r in recs:
            by_task[r["task_id"]].append(r["summary"])
        sums = [r["summary"] for r in recs]
        fb = Counter(s["first_break"] for s in sums)
        hat = sum(all(s["strict_pass"] for s in v) for v in by_task.values()) / len(by_task)
        L.append(f"| {name} | {recs[0]['judge']} | {len(sums)} | {st.mean(s['turns_held'] for s in sums):.2f} | "
                 f"{sum(s['strict_pass'] for s in sums)}/{len(sums)} | {hat:.0%} | "
                 f"{'/'.join(str(fb.get(i, 0)) for i in range(5))} |")
        for tid, v in sorted(by_task.items()):
            checks = Counter(c for s in v for cs in s["broken_checks"].values() for c in cs)
            detail.append(f"| {name} | {tid} | {' '.join(str(s['turns_held']) for s in v)} | "
                          f"{', '.join(str(s['first_break']) for s in v)} | {dict(checks) or '-'} |")
    L += ["", "| Run | Task | Turns held per trial | First break per trial | Broken checks (count over turns) |",
          "|---|---|---|---|---|"] + detail
    return L


if __name__ == "__main__":
    main()
